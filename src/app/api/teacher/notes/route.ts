function notImplemented(err: unknown): Response {
  const detail = err instanceof Error ? err.message : "not wired yet";
  return Response.json({ error: "not_implemented", detail }, { status: 501 });
}

export async function GET(request: Request) {
  let classId: string;
  try {
    ({ classId } = requireTeacher(request));
  } catch (err) {
    return notImplemented(err);
  }

  try {
    const materials = await dbListMaterials(classId);
    return Response.json(materials);
  } catch (err) {
    return notImplemented(err);
  }
}

export async function POST(request: Request) {
  let teacherId: string;
  let classId: string;
  try {
    ({ teacherId, classId } = requireTeacher(request));
  } catch (err) {
    return notImplemented(err);
  }

  const parsed = NotesCreateBody.safeParse(await request.json().catch(() => null));
  if (!parsed.success) {
    return Response.json({ error: "invalid_request", issues: parsed.error.issues }, { status: 400 });
  }

  const doc: Omit<Material, "id" | "createdAt"> = {
    classId,
    teacherId,
    label: parsed.data.label,
    sourceType: parsed.data.sourceType,
    rawText: parsed.data.rawText,
    confirmedText: "", // empty until the teacher confirms
    status: "draft",
    confirmedAt: null,
  };

  try {
    const created = await dbInsertMaterial(doc);
    return Response.json(created, { status: 201 });
  } catch (err) {
    return notImplemented(err);
  }
}
