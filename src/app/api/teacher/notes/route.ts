import { z } from "zod";
import type { Material } from "@/lib/types";

// Request body for creating a note. NOTE: teacherId/classId are NEVER taken from
// the body — they always come from the session (requireTeacher).
const NotesCreateBody = z.object({
  label: z.enum(["taught", "reference"]),
  sourceType: z.enum(["text", "photo", "pdf"]),
  rawText: z.string().min(1).max(100_000),
});
type NotesCreateBody = z.infer<typeof NotesCreateBody>;

// SEAM (Person B): `import { requireTeacher } from "@/lib/auth/session"`.
